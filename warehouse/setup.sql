-- One-time Snowflake setup for the PriceCatcher warehouse.
-- Run as ACCOUNTADMIN in a Snowsight worksheet (a free trial account works).
-- Replace <PUBLIC_KEY> with your public key first (see warehouse/README.md).

USE ROLE ACCOUNTADMIN;

-- Compute: the smallest warehouse, paused after 60 seconds idle so a trial's credits last.
CREATE WAREHOUSE IF NOT EXISTS PRICECATCHER_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- Spending guard: stop the warehouse if it uses 5 credits in a month.
CREATE RESOURCE MONITOR IF NOT EXISTS PRICECATCHER_MONITOR
  WITH CREDIT_QUOTA = 5 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE PRICECATCHER_WH SET RESOURCE_MONITOR = PRICECATCHER_MONITOR;

-- Storage: RAW holds files as loaded; dbt builds STAGING and MARTS.
CREATE DATABASE IF NOT EXISTS PRICECATCHER;
CREATE SCHEMA IF NOT EXISTS PRICECATCHER.RAW;

CREATE STAGE IF NOT EXISTS PRICECATCHER.RAW.LANDING
  FILE_FORMAT = (TYPE = PARQUET)
  COMMENT = 'Monthly PriceCatcher Parquet files, re-encoded to Snappy by warehouse/load.py';

CREATE TABLE IF NOT EXISTS PRICECATCHER.RAW.PRICES (
  date DATE, premise_code NUMBER(38,0), item_code NUMBER(38,0), price FLOAT,
  year_month VARCHAR, _source_file VARCHAR, _ingested_at TIMESTAMP_TZ
) CLUSTER BY (year_month);

CREATE TABLE IF NOT EXISTS PRICECATCHER.RAW.LOOKUP_ITEM (
  item_code NUMBER(38,0), item VARCHAR, unit VARCHAR, item_group VARCHAR, item_category VARCHAR,
  _source_file VARCHAR, _ingested_at TIMESTAMP_TZ
);

CREATE TABLE IF NOT EXISTS PRICECATCHER.RAW.LOOKUP_PREMISE (
  premise_code NUMBER(38,0), premise VARCHAR, address VARCHAR, premise_type VARCHAR,
  state VARCHAR, district VARCHAR, _source_file VARCHAR, _ingested_at TIMESTAMP_TZ
);

-- One role for the pipeline: it loads RAW and lets dbt create its own schemas.
CREATE ROLE IF NOT EXISTS PRICECATCHER_LOADER;
GRANT USAGE ON WAREHOUSE PRICECATCHER_WH TO ROLE PRICECATCHER_LOADER;
GRANT USAGE, CREATE SCHEMA ON DATABASE PRICECATCHER TO ROLE PRICECATCHER_LOADER;
GRANT USAGE ON SCHEMA PRICECATCHER.RAW TO ROLE PRICECATCHER_LOADER;
GRANT READ, WRITE ON STAGE PRICECATCHER.RAW.LANDING TO ROLE PRICECATCHER_LOADER;
GRANT SELECT, INSERT, DELETE ON ALL TABLES IN SCHEMA PRICECATCHER.RAW TO ROLE PRICECATCHER_LOADER;
GRANT ROLE PRICECATCHER_LOADER TO ROLE SYSADMIN;

-- A service user that signs in with a key pair (no password, no MFA prompt),
-- for GitHub Actions and local runs.
CREATE USER IF NOT EXISTS PRICECATCHER_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = PRICECATCHER_LOADER
  DEFAULT_WAREHOUSE = PRICECATCHER_WH
  RSA_PUBLIC_KEY = '<PUBLIC_KEY>';
GRANT ROLE PRICECATCHER_LOADER TO USER PRICECATCHER_SVC;
